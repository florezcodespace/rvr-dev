-- ================================================================== reglas
-- Dos reglas que una llave foránea sola no puede expresar.

-- 1. La cuenta de un cliente o de un técnico tiene el rol que corresponde.
--    Una FK a usuarios no distingue roles: sin esto se podía colgar la ficha
--    de un técnico de la cuenta de un cliente.
--    Uso: exigir_rol('<columna>', '<rol>' [, '<otro rol>' ...])
CREATE FUNCTION exigir_rol() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  usuario int  := (to_jsonb(NEW) ->> TG_ARGV[0])::int;
  rol     text;
BEGIN
  IF usuario IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT r.nombre INTO rol
    FROM usuarios u JOIN roles r ON r.id = u.rol_id
   WHERE u.id = usuario;

  IF rol IS NULL OR NOT rol = ANY (TG_ARGV[1:]) THEN
    RAISE EXCEPTION '%.% = %: el usuario debe tener rol %, y tiene rol %',
      TG_TABLE_NAME, TG_ARGV[0], usuario,
      array_to_string(TG_ARGV[1:], ' o '), coalesce(rol, '(no existe)')
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END $$;

CREATE TRIGGER tg_clientes_rol BEFORE INSERT OR UPDATE OF usuario_id
  ON clientes FOR EACH ROW EXECUTE FUNCTION exigir_rol('usuario_id', 'cliente');
CREATE TRIGGER tg_tecnicos_rol BEFORE INSERT OR UPDATE OF usuario_id
  ON tecnicos FOR EACH ROW EXECUTE FUNCTION exigir_rol('usuario_id', 'tecnico');

-- 2. Nadie abona más de lo que se debe, ni sobre una venta anulada.
--    Los reembolsados no cuentan como abonado.
CREATE FUNCTION validar_abono() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  total   numeric;
  estado_ estado_venta;
  abonado numeric;
BEGIN
  IF NEW.estado = 'reembolsado' THEN
    RETURN NEW;
  END IF;

  -- FOR UPDATE: dos abonos simultáneos a la misma venta se atienden en fila.
  SELECT v.monto_total, v.estado INTO total, estado_
    FROM ventas v WHERE v.id = NEW.venta_id FOR UPDATE;

  IF estado_ = 'anulada' THEN
    RAISE EXCEPTION 'La venta % está anulada y no recibe abonos', NEW.venta_id
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT coalesce(sum(a.monto), 0) INTO abonado
    FROM abonos a
   WHERE a.venta_id = NEW.venta_id
     AND a.estado <> 'reembolsado'
     AND a.id IS DISTINCT FROM NEW.id;

  IF abonado + NEW.monto > total THEN
    RAISE EXCEPTION 'El abono de % supera el saldo de la venta % (saldo: %)',
      NEW.monto, NEW.venta_id, total - abonado
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END $$;

CREATE TRIGGER tg_abonos_saldo BEFORE INSERT OR UPDATE OF monto, estado, venta_id
  ON abonos FOR EACH ROW EXECUTE FUNCTION validar_abono();

-- ==================================================================== vista
-- Lo que antes se guardaba (saldo_pendiente, estado_pago) y ahora se calcula.
-- Se consulta igual que una tabla:  SELECT * FROM v_ventas WHERE saldo > 0;

CREATE VIEW v_ventas AS
SELECT
  v.id,
  v.orden_id,
  o.cliente_id,
  v.monto_total,
  coalesce(ab.abonado, 0)                         AS abonado,
  v.monto_total - coalesce(ab.abonado, 0)         AS saldo,
  CASE
    WHEN v.estado = 'anulada'                      THEN 'anulada'
    WHEN coalesce(ab.abonado, 0) >= v.monto_total  THEN 'pagado'
    WHEN coalesce(ab.abonado, 0) > 0               THEN 'parcial'
    ELSE                                                'pendiente'
  END                                             AS estado_pago,
  v.estado,
  v.fecha_venta
FROM ventas v
JOIN ordenes_servicio o ON o.id = v.orden_id
LEFT JOIN LATERAL (
  SELECT sum(a.monto) AS abonado
    FROM abonos a
   WHERE a.venta_id = v.id AND a.estado <> 'reembolsado'
) ab ON true;

COMMIT;
