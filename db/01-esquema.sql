-- CA_36_04 / CA_39_03 · El monto total de la cotización es la suma de su detalle
CREATE FUNCTION fn_monto_cotizacion() RETURNS trigger AS $$
DECLARE
  cot int := coalesce(NEW.cotizacion_id, OLD.cotizacion_id);
BEGIN
  UPDATE cotizacion
     SET monto_total = coalesce((SELECT sum(subtotal) FROM detalle_cotizacion
                                  WHERE cotizacion_id = cot), 0)
   WHERE id = cot;
  IF TG_OP = 'UPDATE' AND OLD.cotizacion_id <> NEW.cotizacion_id THEN
    UPDATE cotizacion
       SET monto_total = coalesce((SELECT sum(subtotal) FROM detalle_cotizacion
                                    WHERE cotizacion_id = OLD.cotizacion_id), 0)
     WHERE id = OLD.cotizacion_id;
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_monto_cotizacion
  AFTER INSERT OR UPDATE OR DELETE ON detalle_cotizacion
  FOR EACH ROW EXECUTE FUNCTION fn_monto_cotizacion();

-- CA_44_02 · Código de orden único e irrepetible: OS-2026-0001
CREATE FUNCTION fn_codigo_orden() RETURNS trigger AS $$
BEGIN
  IF NEW.codigo_orden IS NULL OR NEW.codigo_orden = '' THEN
    NEW.codigo_orden := 'OS-' || to_char(NEW.fecha_creacion, 'YYYY') || '-' ||
                        lpad(NEW.id::text, 4, '0');
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_codigo_orden
  BEFORE INSERT ON orden
  FOR EACH ROW EXECUTE FUNCTION fn_codigo_orden();

-- Observación de la matriz v5: «nada impide que una orden mezcle diagnósticos
-- de dos clientes». Ahora la base lo impide, y solo acepta ítems aprobados.
CREATE FUNCTION fn_detalle_orden_mismo_cliente() RETURNS trigger AS $$
DECLARE
  cliente_nuevo int;
  estado_cot    varchar(20);
  otro_cliente  int;
BEGIN
  SELECT c.cliente_id, c.estado INTO cliente_nuevo, estado_cot
    FROM detalle_cotizacion dc JOIN cotizacion c ON c.id = dc.cotizacion_id
   WHERE dc.id = NEW.detalle_cotizacion_id;

  IF estado_cot <> 'aprobada' THEN
    RAISE EXCEPTION 'Solo los ítems de una cotización aprobada pueden pasar a una orden'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_detalle_orden_aprobada';
  END IF;

  SELECT c.cliente_id INTO otro_cliente
    FROM detalle_orden d
    JOIN detalle_cotizacion dc ON dc.id = d.detalle_cotizacion_id
    JOIN cotizacion c          ON c.id = dc.cotizacion_id
   WHERE d.orden_id = NEW.orden_id AND d.id <> coalesce(NEW.id, -1)
   LIMIT 1;

  IF otro_cliente IS NOT NULL AND otro_cliente <> cliente_nuevo THEN
    RAISE EXCEPTION 'Una orden no puede mezclar ítems de dos clientes'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_detalle_orden_cliente';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_detalle_orden_cliente
  BEFORE INSERT OR UPDATE OF detalle_cotizacion_id, orden_id ON detalle_orden
  FOR EACH ROW EXECUTE FUNCTION fn_detalle_orden_mismo_cliente();

-- CA_58_02 / CA_58_04 / CA_57_01 / CA_57_02 / CA_57_04
-- Valida el abono y deja la venta al día: saldo y estado de pago.
CREATE FUNCTION fn_abono_venta() RETURNS trigger AS $$
DECLARE
  v ventas%ROWTYPE;
  abonado numeric;
BEGIN
  SELECT * INTO v FROM ventas WHERE id = NEW.venta_id FOR UPDATE;
  IF v.estado_pago = 'anulada' THEN
    RAISE EXCEPTION 'La venta está anulada: no recibe abonos'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_abono_venta_anulada';
  END IF;

  SELECT coalesce(sum(monto), 0) INTO abonado FROM abonos WHERE venta_id = v.id;
  IF abonado + NEW.monto > v.monto_total THEN
    RAISE EXCEPTION 'El abono supera el saldo pendiente de la venta'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_abono_saldo';
  END IF;

  UPDATE ventas
     SET saldo_pendiente = monto_total - (abonado + NEW.monto),
         estado_pago = CASE
           WHEN monto_total - (abonado + NEW.monto) = 0 THEN 'pagada'
           WHEN abonado + NEW.monto >= monto_anticipo   THEN 'abonada'
           ELSE 'pendiente_anticipo' END
   WHERE id = v.id;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_abono_venta
  BEFORE INSERT ON abonos
  FOR EACH ROW EXECUTE FUNCTION fn_abono_venta();

-- CA_28_03 · Una franja no se cruza con otra del mismo técnico en la misma fecha
CREATE FUNCTION fn_franja_sin_cruce() RETURNS trigger AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM disponibilidad
     WHERE tecnico_id = NEW.tecnico_id AND fecha = NEW.fecha
       AND id <> coalesce(NEW.id, -1)
       AND NEW.hora_inicio < hora_fin AND hora_inicio < NEW.hora_fin
  ) THEN
    RAISE EXCEPTION 'La franja se cruza con otra del mismo técnico en esa fecha'
      USING ERRCODE = 'exclusion_violation', CONSTRAINT = 'ck_franja_cruce';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_franja_sin_cruce
  BEFORE INSERT OR UPDATE OF tecnico_id, fecha, hora_inicio, hora_fin ON disponibilidad
  FOR EACH ROW EXECUTE FUNCTION fn_franja_sin_cruce();

-- Móvil HU_10 · Cada cambio de estado de la orden queda en su historial.
-- Quién lo hizo llega en la variable de sesión rvr.usuario_id (la pone la API).
CREATE FUNCTION fn_historial_orden() RETURNS trigger AS $$
DECLARE
  quien int := nullif(current_setting('rvr.usuario_id', true), '')::int;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO historial_orden (orden_id, estado_anterior, estado_nuevo, descripcion, usuario_id, fecha)
    VALUES (NEW.id, NULL, NEW.estado, 'Orden creada', quien, NEW.fecha_creacion);
  ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN
    INSERT INTO historial_orden (orden_id, estado_anterior, estado_nuevo, descripcion, usuario_id)
    VALUES (NEW.id, OLD.estado, NEW.estado,
            coalesce(nullif(current_setting('rvr.motivo', true), ''), 'Cambio de estado'), quien);
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER tg_historial_orden
  AFTER INSERT OR UPDATE OF estado ON orden
  FOR EACH ROW EXECUTE FUNCTION fn_historial_orden();

