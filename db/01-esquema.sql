-- CA_56_01 / CA_56_02 · Estado de cuenta calculado de cada venta, con su
-- cliente (orden → detalle_orden → detalle_cotizacion → cotizacion → cliente).
CREATE VIEW v_ventas AS
SELECT v.id, v.orden_id, v.monto_total, v.monto_anticipo, v.estado_pago, v.fecha_venta,
       coalesce(a.abonado, 0)                     AS abonado,
       v.monto_total - coalesce(a.abonado, 0)     AS saldo,
       cli.cliente_id
  FROM ventas v
  LEFT JOIN (SELECT venta_id, sum(monto) AS abonado FROM abonos GROUP BY venta_id) a
         ON a.venta_id = v.id
  LEFT JOIN LATERAL (
    SELECT c.cliente_id
      FROM detalle_orden d
      JOIN detalle_cotizacion dc ON dc.id = d.detalle_cotizacion_id
      JOIN cotizacion c          ON c.id = dc.cotizacion_id
     WHERE d.orden_id = v.orden_id
     LIMIT 1
  ) cli ON true;

-- La orden con su cliente y su cotización de origen: la usan casi todas las
-- consultas, así el camino de cuatro tablas se escribe una sola vez.
CREATE VIEW v_orden_cliente AS
SELECT o.id AS orden_id, x.cliente_id, x.cotizacion_id
  FROM orden o
  LEFT JOIN LATERAL (
    SELECT c.cliente_id, c.id AS cotizacion_id
      FROM detalle_orden d
      JOIN detalle_cotizacion dc ON dc.id = d.detalle_cotizacion_id
      JOIN cotizacion c          ON c.id = dc.cotizacion_id
     WHERE d.orden_id = o.id
     ORDER BY c.fecha_cotizacion
     LIMIT 1
  ) x ON true;

